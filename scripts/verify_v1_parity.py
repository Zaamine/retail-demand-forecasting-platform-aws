"""Verify frozen V1 predictions against the refactored feature pipeline.

The script rebuilds historical forecasts for three representative
store-family series without retraining or modifying the frozen model.
"""

from pathlib import Path

import numpy as np
import pandas as pd
from xgboost import XGBRegressor

from forecasting.build_forecast import build_forecast_frame_v1
from forecasting.model_inputs import (
    load_model_input_schema,
    prepare_xgboost_X,
)


ROOT = Path(__file__).resolve().parents[1]
ORIGIN = pd.Timestamp("2017-08-01")

# Representative series previously audited in Notebook 05.
SAMPLES = (
    (27, "GROCERY I"),
    (35, "SEAFOOD"),
    (40, "HOME AND KITCHEN I"),
)

KEYS = ["store_nbr", "family", "horizon", "target_date"]


def load_selected_sales(path: Path) -> pd.DataFrame:
    """Load only the selected series, without loading the full CSV into RAM."""

    if not path.exists():
        raise FileNotFoundError(f"Sales file not found: {path}")

    chunks = []

    # Read the large original dataset incrementally to limit memory usage.
    for chunk in pd.read_csv(
        path,
        usecols=["date", "store_nbr", "family", "sales"],
        parse_dates=["date"],
        dtype={
            "store_nbr": "int16",
            "family": "string",
            "sales": "float32",
        },
        chunksize=250_000,
    ):
        # Restrict data to information available at the forecast origin.
        historical = chunk["date"].le(ORIGIN)
        selected = pd.Series(False, index=chunk.index)

        for store, family in SAMPLES:
            selected |= (
                chunk["store_nbr"].eq(store)
                & chunk["family"].eq(family)
            )

        subset = chunk.loc[historical & selected]

        if not subset.empty:
            chunks.append(subset)

    if not chunks:
        raise ValueError("No historical sales found for selected series.")

    return pd.concat(chunks, ignore_index=True)


def main() -> None:
    """Compare reconstructed predictions with the frozen holdout artifact."""

    artifacts = ROOT / "artifacts" / "global_xgboost"

    # Load forecasts generated by the original Notebook 05.
    reference = pd.read_parquet(
        artifacts / "final_holdout_forecast.parquet"
    )

    reference["target_date"] = pd.to_datetime(
        reference["target_date"]
    )
    reference["family"] = reference["family"].astype(str)

    # Load the frozen predictor order and categorical vocabularies.
    schema = load_model_input_schema(
        artifacts / "point_forecast_model_contract_v1.json",
        ROOT / "configs/global_xgboost/categories_v1.json",
    )

    # Reload the exact trained V1 model rather than fitting a new model.
    model = XGBRegressor(enable_categorical=True)
    model.load_model(
        artifacts / "xgboost_point_forecast_v1.json"
    )

    # Confirm that the serialized model expects the frozen feature schema.
    if model.get_booster().feature_names != list(schema.features):
        raise ValueError("Model features do not match the V1 contract.")

    history = load_selected_sales(
        ROOT / "data/raw/favorita/train/train.csv"
    )

    comparisons = []

    for store, family in SAMPLES:

        # Isolate one series to avoid rebuilding the entire portfolio.
        series_history = history.loc[
            history["store_nbr"].eq(store)
            & history["family"].eq(family),
            ["store_nbr", "family", "date", "sales"],
        ].copy()

        if series_history.empty:
            raise ValueError(f"Missing series: {store}, {family}")

        # Rebuild historical and seasonal features using the new modules.
        frame = build_forecast_frame_v1(
            series_history,
            ORIGIN,
        )

        X = prepare_xgboost_X(frame, schema)

        # Reproduce the original inference and non-negative clipping.
        raw_predictions = model.predict(X).astype("float64")

        rebuilt = frame[KEYS].copy()
        rebuilt["family"] = rebuilt["family"].astype(str)
        rebuilt["prediction_raw_new"] = raw_predictions
        rebuilt["prediction_new"] = np.clip(
            raw_predictions, 0, None
        )

        # Extract the original predictions for the same business keys.
        expected = reference.loc[
            reference["store_nbr"].eq(store)
            & reference["family"].eq(family),
            KEYS + ["prediction_raw", "prediction"],
        ]

        if len(expected) != 14:
            raise ValueError(
                f"Expected 14 reference predictions for {store}/{family}."
            )

        # Join on business keys, never on row positions.
        comparison = rebuilt.merge(
            expected,
            on=KEYS,
            how="inner",
            validate="one_to_one",
        )

        if len(comparison) != 14:
            raise ValueError(
                f"Forecast keys do not match for {store}/{family}."
            )

        # Measure differences before and after non-negative clipping.
        comparison["abs_diff_raw"] = (
            comparison["prediction_raw_new"]
            - comparison["prediction_raw"]
        ).abs()

        comparison["abs_diff_clipped"] = (
            comparison["prediction_new"]
            - comparison["prediction"]
        ).abs()

        comparisons.append(comparison)

        print(
            f"{store:>2} / {family:<20} | "
            f"max raw difference: "
            f"{comparison['abs_diff_raw'].max():.8f}"
        )

    result = pd.concat(comparisons, ignore_index=True)

    max_abs = max(
        result["abs_diff_raw"].max(),
        result["abs_diff_clipped"].max(),
    )

    print(
        f"\nCompared predictions: {len(result)} "
        f"/ max absolute difference: {max_abs:.8f}"
    )

    # A strict tolerance detects changes in feature construction.
    # Any failure must be investigated before production deployment.
    if not np.isfinite(max_abs) or max_abs > 1e-4:
        print(
            result.nlargest(5, "abs_diff_raw")[
                KEYS + [
                    "prediction_raw_new",
                    "prediction_raw",
                    "abs_diff_raw",
                ]
            ].to_string(index=False)
        )

        raise AssertionError(
            "V1 prediction parity failed. Investigate before deploying."
        )

    print("V1 sampled prediction parity: PASSED")


if __name__ == "__main__":
    main()
